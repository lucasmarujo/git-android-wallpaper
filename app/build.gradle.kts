val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use(::load)
}

fun signingValue(key: String, environmentVariable: String): String? =
    keystoreProperties.getProperty(key) ?: providers.environmentVariable(environmentVariable).orNull

val githubClientId: String = providers.gradleProperty("gitWallpaper.githubClientId").getOrElse("")

